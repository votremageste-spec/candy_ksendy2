/** Заготовка компонента: заполняем только то, что отличается от значений по умолчанию. */
function component(
  data: Omit<DessertComponent, 'needsPriceReview' | 'inStock' | 'imageUrl'> &
    Partial<Pick<DessertComponent, 'needsPriceReview' | 'inStock' | 'imageUrl'>>,
): DessertComponent {
  return {
    needsPriceReview: false,
    inStock: true,
    imageUrl: '',
    ...data,
  };
}

